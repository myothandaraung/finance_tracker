import 'dart:typed_data';

import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

import '../money/money.dart';
import '../utils/date_utils.dart';
import '../../features/orders/domain/order.dart';
import '../../features/quotations/domain/quotation.dart';

/// Builds the printable documents (quotation and order) as PDF.
class DocumentPdf {
  const DocumentPdf._();

  static const _currency = '₱';

  /// A quotation that can be sent to a customer.
  static Future<Uint8List> buildQuotation({
    required String businessName,
    required Quotation quotation,
  }) async {
    final document = pw.Document(
      title: 'Quotation ${quotation.quotationNo}',
      author: businessName,
    );

    document.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(36),
        build: (context) => [
          _header(
            businessName: businessName,
            title: 'QUOTATION',
            number: quotation.quotationNo,
            status: quotation.status.label,
          ),
          pw.SizedBox(height: 18),
          _parties(
            left: [
              _party('Customer', quotation.customerName),
            ],
            right: [
              _party('Issued', AppDate.format(quotation.createdAt)),
              _party(
                'Valid until',
                quotation.validUntil == null
                    ? '—'
                    : AppDate.format(quotation.validUntil),
              ),
            ],
          ),
          pw.SizedBox(height: 18),
          _itemsTable(
            rows: [
              for (final item in quotation.items)
                [
                  item.description,
                  item.quantity.toString(),
                  _money(item.unitPrice),
                  _money(item.lineTotal),
                ],
            ],
          ),
          pw.SizedBox(height: 14),
          _totals(
            rows: [
              ['Subtotal', _money(quotation.subtotal)],
              ['Discount', '- ${_money(quotation.discountAmount)}'],
              ['Total', _money(quotation.totalAmount)],
            ],
          ),
          if (quotation.notes != null && quotation.notes!.isNotEmpty) ...[
            pw.SizedBox(height: 20),
            pw.Text('Notes', style: pw.TextStyle(fontWeight: pw.FontWeight.bold)),
            pw.SizedBox(height: 4),
            pw.Text(quotation.notes!),
          ],
          pw.SizedBox(height: 28),
          pw.Divider(),
          pw.SizedBox(height: 10),
          pw.Text(
            'Generated by MTO Finance',
            style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey600),
          ),
        ],
      ),
    );

    return document.save();
  }

  /// An order with its payment summary.
  static Future<Uint8List> buildOrder({
    required String businessName,
    required OrderDetail detail,
  }) async {
    final order = detail.order;
    final document = pw.Document(
      title: 'Order ${order.orderNo}',
      author: businessName,
    );

    document.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(36),
        build: (context) => [
          _header(
            businessName: businessName,
            title: 'ORDER',
            number: order.orderNo,
            status: order.status.label,
          ),
          pw.SizedBox(height: 18),
          _parties(
            left: [_party('Customer', order.customerName)],
            right: [
              _party('Created', AppDate.format(order.createdAt)),
              _party(
                'Due date',
                order.dueDate == null ? '—' : AppDate.format(order.dueDate),
              ),
              _party('Delivered', AppDate.format(order.deliveredAt)),
            ],
          ),
          pw.SizedBox(height: 18),
          _itemsTable(
            rows: [
              for (final item in detail.items)
                [
                  item.description,
                  item.quantity.toString(),
                  _money(item.unitPrice),
                  _money(item.lineTotal),
                ],
            ],
          ),
          pw.SizedBox(height: 14),
          _totals(
            rows: [
              ['Subtotal', _money(order.subtotal)],
              ['Discount', '- ${_money(order.discountAmount)}'],
              ['Total', _money(order.totalAmount)],
              ['Paid', _money(detail.financials.paidAmount)],
              ['Outstanding', _money(detail.financials.outstandingAmount)],
              ['Actual cost', _money(detail.financials.actualCost)],
              ['Profit', _money(detail.financials.profit)],
            ],
          ),
          if (order.notes != null && order.notes!.isNotEmpty) ...[
            pw.SizedBox(height: 20),
            pw.Text('Notes', style: pw.TextStyle(fontWeight: pw.FontWeight.bold)),
            pw.SizedBox(height: 4),
            pw.Text(order.notes!),
          ],
          if (detail.payments.isNotEmpty) ...[
            pw.SizedBox(height: 20),
            pw.Text('Payments', style: pw.TextStyle(fontWeight: pw.FontWeight.bold)),
            pw.SizedBox(height: 6),
            pw.TableHelper.fromTextArray(
              headers: const ['Date', 'Type', 'Method', 'Amount'],
              data: [
                for (final payment in detail.payments)
                  [
                    AppDate.format(payment.paidAt),
                    payment.kind,
                    payment.method,
                    _money(payment.amount),
                  ],
              ],
              headerStyle: pw.TextStyle(
                fontSize: 9,
                fontWeight: pw.FontWeight.bold,
              ),
              cellStyle: const pw.TextStyle(fontSize: 9),
              border: null,
            ),
          ],
          pw.SizedBox(height: 28),
          pw.Divider(),
          pw.SizedBox(height: 10),
          pw.Text(
            'Generated by MTO Finance',
            style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey600),
          ),
        ],
      ),
    );

    return document.save();
  }

  static pw.Widget _header({
    required String businessName,
    required String title,
    required String number,
    required String status,
  }) {
    return pw.Row(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
      children: [
        pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            pw.Text(
              businessName,
              style: pw.TextStyle(fontSize: 18, fontWeight: pw.FontWeight.bold),
            ),
            pw.SizedBox(height: 4),
            pw.Text(
              title,
              style: const pw.TextStyle(
                fontSize: 12,
                color: PdfColors.grey700,
                letterSpacing: 2,
              ),
            ),
          ],
        ),
        pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.end,
          children: [
            pw.Text(
              number,
              style: pw.TextStyle(fontSize: 14, fontWeight: pw.FontWeight.bold),
            ),
            pw.SizedBox(height: 4),
            pw.Text(
              status,
              style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey700),
            ),
          ],
        ),
      ],
    );
  }

  static pw.Widget _parties({
    required List<pw.Widget> left,
    required List<pw.Widget> right,
  }) {
    return pw.Row(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
      children: [
        pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: left,
        ),
        pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.end,
          children: right,
        ),
      ],
    );
  }

  static pw.Widget _party(String label, String value) {
    return pw.Container(
      margin: const pw.EdgeInsets.only(bottom: 4),
      child: pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Text(
            label,
            style: const pw.TextStyle(fontSize: 8.5, color: PdfColors.grey600),
          ),
          pw.Text(value, style: const pw.TextStyle(fontSize: 10)),
        ],
      ),
    );
  }

  static pw.Widget _itemsTable({required List<List<String>> rows}) {
    return pw.TableHelper.fromTextArray(
      headers: const ['Item', 'Qty', 'Unit price', 'Amount'],
      data: rows,
      headerStyle: pw.TextStyle(fontSize: 9, fontWeight: pw.FontWeight.bold),
      cellStyle: const pw.TextStyle(fontSize: 9),
      cellAlignments: {
        1: pw.Alignment.centerRight,
        2: pw.Alignment.centerRight,
        3: pw.Alignment.centerRight,
      },
      border: null,
    );
  }

  static pw.Widget _totals({required List<List<String>> rows}) {
    return pw.Align(
      alignment: pw.Alignment.centerRight,
      child: pw.SizedBox(
        width: 220,
        child: pw.TableHelper.fromTextArray(
          data: rows,
          cellStyle: const pw.TextStyle(fontSize: 9.5),
          cellAlignments: {1: pw.Alignment.centerRight},
          border: null,
        ),
      ),
    );
  }

  static String _money(Money value) => '$_currency${value.plain}';
}
